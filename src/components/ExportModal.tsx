import React, { useState } from 'react';
import { CallAnalysisResult } from '../types/sales';
import { X, Copy, Check, Printer, FileText, CheckCircle2 } from 'lucide-react';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  call: CallAnalysisResult;
}

export const ExportModal: React.FC<ExportModalProps> = ({ isOpen, onClose, call }) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdownReport = () => {
    return `# DealPulse Sales Coaching Brief
**Call Title:** ${call.callTitle}
**Date:** ${call.recordedAt || 'Recent'}
**Duration:** ${call.callDurationFormatted}
**Overall Score:** ${call.scorecard.overallScore}/100
**Talk-to-Listen Ratio:** Rep ${call.scorecard.talkRatioRep}% / Buyer ${call.scorecard.talkRatioProspect}%
**Deal Forecast:** ${call.coachingCard.dealOutcomeProjection} (${call.coachingCard.dealStage} Stage)

---

## 🎯 Executive Summary
${call.coachingCard.executiveSummary}

**Primary Buyer Pain:** ${call.coachingCard.primaryBuyerPain}
**Next Steps:** ${call.scorecard.nextStepSummary}

---

## ✅ 3 Things Done Well (High Leverage)
${call.coachingCard.thingsDoneWell
  .map(
    (item, idx) => `### ${idx + 1}. ${item.title} (${item.timestamp})
- **Quote:** "${item.quote}"
- **Methodology:** ${item.salesPrinciple}
- **Impact:** ${item.impactReason}
- **Score Contribution:** ${item.scoreContribution}
`
  )
  .join('\n')}

---

## ⚠️ 3 Missed Opportunities & Turnaround Scripts
${call.coachingCard.missedOpportunities
  .map(
    (item, idx) => `### ${idx + 1}. ${item.title} (${item.timestamp}) [${item.dealRisk} Risk]
- **Observation:** ${item.whatWentWrong}
- **Recommended Turnaround Script:**
  > "${item.recommendedAlternative}"
- **Methodology Rule:** ${item.frameworkAdvice}
`
  )
  .join('\n')}

---
*Generated by DealPulse AI Sales Coaching Intelligence*`;
  };

  const reportText = generateMarkdownReport();

  const handleCopy = () => {
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-md">
      <div className="bg-slate-900 border border-slate-800 rounded-3xl w-full max-w-2xl max-h-[85vh] flex flex-col shadow-2xl overflow-hidden">
        <div className="flex items-center justify-between p-5 border-b border-slate-800">
          <div className="flex items-center gap-2">
            <div className="p-2 rounded-xl bg-indigo-500/10 text-indigo-400 border border-indigo-500/20">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base font-bold text-white">Export Sales Coaching Brief</h3>
              <p className="text-xs text-slate-400">
                Ready to paste into CRM, Slack, or manager 1:1 prep notes
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 text-slate-400 hover:text-white rounded-xl hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        <div className="p-6 overflow-y-auto flex-1 font-mono text-xs">
          <textarea
            readOnly
            value={reportText}
            rows={18}
            className="w-full bg-slate-950 border border-slate-800 rounded-2xl p-4 text-slate-200 resize-none focus:outline-none scrollbar-thin scrollbar-thumb-slate-800"
          />
        </div>

        <div className="p-5 border-t border-slate-800 bg-slate-950/80 flex items-center justify-between">
          <button
            onClick={handlePrint}
            className="flex items-center gap-2 px-4 py-2 rounded-xl border border-slate-800 hover:bg-slate-800 text-xs text-slate-300 font-medium transition-colors"
          >
            <Printer className="w-4 h-4" /> Print / Save PDF
          </button>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white font-semibold text-xs shadow-lg shadow-indigo-600/30 transition-all active:scale-95"
            >
              {copied ? (
                <>
                  <Check className="w-4 h-4 text-emerald-300" /> Copied Markdown
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4" /> Copy Brief to Clipboard
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
